    $un = $rows.Count - $shipN
    $m = $famMeta[$fam]
    [void]$md.AppendLine("| $fam | ``$($m.Ext)`` | ``$($m.Def)`` | $($m.Entry) | $($rows.Count) | $shipN | $un |")
}
