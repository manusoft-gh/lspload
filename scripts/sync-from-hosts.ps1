function Write-FamilyTable([string]$fam) {
    [void]$md.AppendLine("## $fam")
    [void]$md.AppendLine('')
    $rows = @($targets | Where-Object { [string]$_.family -eq $fam })
    if ($rows.Count -eq 0) {
        [void]$md.AppendLine('| Id | Arch | Toolset | SDK | Ship | PE | Marketing |')
        [void]$md.AppendLine('|----|------|---------|-----|------|----|-----------|')
        [void]$md.AppendLine('*(no targets)*')
        [void]$md.AppendLine('')
        return
    }
    [void]$md.AppendLine('| Id | Arch | Toolset | SDK | Ship | PE | Marketing |')
    [void]$md.AppendLine('|----|------|---------|-----|------|----|-----------|')
    foreach ($row in $rows) {
        $mkt = (Get-StrList $row.marketing) -join ', '
        $pe = "$($row.outputName)$($row.ext)"
        $ship = Get-YesNo ([bool]$row.ship)
        [void]$md.AppendLine("| $($row.id) | $($row.arch) | $($row.toolset) | $($row.sdkEnv) | $ship | $pe | $mkt |")
    }
    [void]$md.AppendLine('')
}

Write-FamilyTable 'ARX'
Write-FamilyTable 'BRX'
Write-FamilyTable 'ZRX'
Write-FamilyTable 'GRX'

[void]$md.AppendLine('## Registry probes')
[void]$md.AppendLine('')
[void]$md.AppendLine('Every row has `reg.appsSuffix`, `reg.loaderStyle`, and `reg.probes[]`. Every probe has `key`, `curVerName`, `curVerHive`, `appsHive`, `writeRoot`.')
[void]$md.AppendLine('')
[void]$md.AppendLine('- Hives: `HKCU32`, `HKCU64`, `HKLM32`, `HKLM64`')
[void]$md.AppendLine('- `writeRoot`: `preferred32` | `preferred64` | `hklm32`')
[void]$md.AppendLine('- Typical detect: CurVer in HKCU* and Applications in HKLM* (ARX 15: both on HKLM32)')
[void]$md.AppendLine('- BRX CurVer value name is `CURVER`')
[void]$md.AppendLine('')

[System.IO.File]::WriteAllText($DocsOut, $md.ToString(), [System.Text.UTF8Encoding]::new($false))

Write-Host "sync-from-hosts.ps1: wrote $CmakeOut ($($targets.Count) targets)"
Write-Host "sync-from-hosts.ps1: wrote $DocsOut"
exit 0
