[void]$md.AppendLine('')
[void]$md.AppendLine('- x86 `outputName`: `LspLoad.{FAM}.{ver}` (no architecture token)')
[void]$md.AppendLine('- x64 `outputName`: `LspLoad.{FAM}.{ver}.x64`')
[void]$md.AppendLine('- `arch` is only `x86` or `x64` (never `Win32` / `X64`)')
[void]$md.AppendLine('- Loader / DestName is row-level (`outputName` + `ext`). Probes do not carry a loader filename.')
[void]$md.AppendLine('')
[void]$md.AppendLine('## Ship vs unshipped')
[void]$md.AppendLine('')
$goldPath = Join-Path $RepoRoot 'docs\gold\LspLoad-6.10-names.txt'
$goldN = 0
if (Test-Path -LiteralPath $goldPath) {
    $goldN = @(Get-Content -LiteralPath $goldPath | ForEach-Object { $_.Trim() } | Where-Object { $_ }).Count
}
$shipN = @($targets | Where-Object { [bool]$_.ship }).Count
[void]$md.AppendLine(('- Gold 6.10 floor: **{0}** PE names in [`docs/gold/LspLoad-6.10-names.txt`](gold/LspLoad-6.10-names.txt), all `ship: true`.' -f $goldN))
[void]$md.AppendLine(('- Matrix `ship: true` rows: **{0}** (matches the floor; extra ship names are allowed after 6.11).' -f $shipN))
[void]$md.AppendLine('- Unshipped: **ZRX.2024** x86 and x64 (`ship: false`). The project exists; ZWCAD 2024 is covered by extra probes on **ZRX.2023** using the 2023 DestName.')
[void]$md.AppendLine('- ZWCAD 2026 is an extra probe on **ZRX.2025** using the **2025** DestName (`LspLoad.ZRX.2025.x64.zrx`). Do not invent a `ZRX.2026` filename.')
[void]$md.AppendLine('')
[void]$md.AppendLine('## Special rows')
[void]$md.AppendLine('')
[void]$md.AppendLine('| Id | Notes |')
[void]$md.AppendLine('|----|-------|')
[void]$md.AppendLine('| ARX.15 | `characterSet` MultiByte, `loaderStyle` acadR15, `writeRoot` hklm32, admin detect only, toolset v60 |')
[void]$md.AppendLine('| ARX.20 | toolset `v110_xp`, `pinWindowsSdk` true |')
[void]$md.AppendLine('| ARX.26.x64 | toolset **v145** (not vcxproj v143), `sdkEnv` ARX2027, `_ACADTARGET=26`, `cxxStandard` 17, `pinWindowsSdk` false |')
[void]$md.AppendLine('| BRX.* | `curVerName` CURVER; x64 keys `Software\Bricsys\Bricscad\V{n}x64` |')
[void]$md.AppendLine('| ZRX.2023 | extra probe `Software\ZWSOFT\ZWCAD\2024` |')
