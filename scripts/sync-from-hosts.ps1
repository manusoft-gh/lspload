# Generate cmake/LspLoadHosts.cmake (and docs/HOSTS.md) from hosts/hosts.json.
# CMake does not parse JSON. Re-run after any hosts.json edit.
# Does not emit Inno fragments (PR 4).
Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$RepoRoot = Split-Path $PSScriptRoot -Parent
$HostsPath = Join-Path $RepoRoot 'hosts\hosts.json'
$CmakeOut = Join-Path $RepoRoot 'cmake\LspLoadHosts.cmake'
$DocsOut = Join-Path $RepoRoot 'docs\HOSTS.md'

function ConvertTo-CMakeString([string]$s) {
    if ($null -eq $s) { $s = '' }
    $s = $s.Replace('\', '\\').Replace('"', '\"')
    return "`"$s`""
}

function Get-StrList($val) {
    if ($null -eq $val) { return @() }
    if ($val -is [string]) { return @($val) }
    return @($val)
}

function ConvertTo-CMakeBool($val) {
    if ($val -eq $true -or "$val" -eq 'True' -or "$val" -eq 'true') { return 'TRUE' }
    return 'FALSE'
}

function ConvertTo-BarList($val) {
    $items = Get-StrList $val
    return ($items -join '|')
}

if (-not (Test-Path -LiteralPath $HostsPath)) {
    Write-Error "Missing $HostsPath"
    exit 1
}

$doc = (Get-Content -LiteralPath $HostsPath -Raw -Encoding UTF8) | ConvertFrom-Json
if ($null -eq $doc) {
    Write-Error 'hosts.json did not parse'
    exit 1
}
if ($doc.PSObject.Properties.Name -contains 'productVersion') {
    Write-Error 'hosts.json must not contain productVersion'
    exit 1
}

$targets = @($doc.targets)
$cmakeDir = Split-Path $CmakeOut -Parent
if (-not (Test-Path -LiteralPath $cmakeDir)) {
    New-Item -ItemType Directory -Path $cmakeDir | Out-Null
}

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('# GENERATED by scripts/sync-from-hosts.ps1 from hosts/hosts.json. Do not hand-edit.')
[void]$sb.AppendLine('# CMake does not parse JSON; re-run sync after any hosts.json change.')
[void]$sb.AppendLine('include_guard(GLOBAL)')
[void]$sb.AppendLine('')
[void]$sb.AppendLine('set(LSPLOAD_HOST_IDS)')

foreach ($row in $targets) {
    $id = [string]$row.id
    [void]$sb.AppendLine("list(APPEND LSPLOAD_HOST_IDS $(ConvertTo-CMakeString $id))")
}

[void]$sb.AppendLine('')

foreach ($row in $targets) {
    $id = [string]$row.id
    $cxx = $row.cxxStandard
    $cxxStr = if ($null -eq $cxx -or "$cxx" -eq '') { '' } else { [string]$cxx }
    $pairs = @(
        @{ K = 'FAMILY'; V = [string]$row.family }
        @{ K = 'VERSION'; V = [string]$row.version }
        @{ K = 'ARCH'; V = [string]$row.arch }
        @{ K = 'EXT'; V = [string]$row.ext }
        @{ K = 'DEF'; V = [string]$row.def }
        @{ K = 'OUTPUT_NAME'; V = [string]$row.outputName }
        @{ K = 'TOOLSET'; V = [string]$row.toolset }
        @{ K = 'SDK_ENV'; V = [string]$row.sdkEnv }
        @{ K = 'SDK_INC'; V = ConvertTo-BarList $row.sdkInc }
        @{ K = 'SDK_LIB'; V = ConvertTo-BarList $row.sdkLib }
        @{ K = 'LIBS'; V = ConvertTo-BarList $row.libs }
        @{ K = 'DEFINES'; V = ConvertTo-BarList $row.defines }
        @{ K = 'CHARACTER_SET'; V = [string]$row.characterSet }
        @{ K = 'CXX_STANDARD'; V = $cxxStr }
    )
    foreach ($p in $pairs) {
        [void]$sb.AppendLine("set(LSPLOAD_H_${id}_$($p.K) $(ConvertTo-CMakeString $p.V))")
    }
    [void]$sb.AppendLine("set(LSPLOAD_H_${id}_PIN_WINDOWS_SDK $(ConvertTo-CMakeBool $row.pinWindowsSdk))")
    [void]$sb.AppendLine("set(LSPLOAD_H_${id}_SHIP $(ConvertTo-CMakeBool $row.ship))")
    [void]$sb.AppendLine('')
}

[System.IO.File]::WriteAllText($CmakeOut, $sb.ToString(), [System.Text.UTF8Encoding]::new($false))

# --- docs/HOSTS.md ---
function Get-YesNo([bool]$b) { if ($b) { 'yes' } else { 'no' } }

$famMeta = [ordered]@{
    ARX = @{ Ext = '.arx'; Def = 'src/RxExports.def'; Entry = 'acrx' }
    BRX = @{ Ext = '.brx'; Def = 'src/RxExports.def'; Entry = 'acrx' }
    ZRX = @{ Ext = '.zrx'; Def = 'src/ZrxExports.def'; Entry = 'zcrx' }
    GRX = @{ Ext = '.grx'; Def = 'src/GrxExports.def'; Entry = 'gcrx' }
}

$md = [System.Text.StringBuilder]::new()
[void]$md.AppendLine('# Host inventory')
[void]$md.AppendLine('')
[void]$md.AppendLine('Generated by `scripts/sync-from-hosts.ps1` from [`hosts/hosts.json`](../hosts/hosts.json). Do not hand-edit.')
[void]$md.AppendLine('')
[void]$md.AppendLine('`hosts.json` has no `productVersion`. Product version lives in [`VERSION`](../VERSION).')
