# --- HostsFiles.iss (Source: lines only; no [Files] header) ---
$fileLines = [System.Collections.Generic.List[string]]::new()
[void]$fileLines.Add('; Generated by scripts/sync-from-hosts.ps1 from hosts/hosts.json. Do not hand-edit.')
[void]$fileLines.Add('; Loader/DestName is row-level. Extra probes (shared years) reuse this DestName.')
[void]$fileLines.Add('')

$prevFam = $null
foreach ($row in $shipRows) {
    $fam = [string]$row.family
    if ($fam -ne $prevFam) {
        [void]$fileLines.Add("; $(Get-FamilyComment $fam)")
        $prevFam = $fam
    }
    $src = "LspLoad\$($row.outputName)$($row.ext)"
    $dest = Get-InnoDestName $row
    $hostTok = [string]$row.family
    $verTok = [string]$row.version
    $archTok = [string]$row.arch
    [void]$fileLines.Add(("Source: `"$src`"; DestDir: `"{app}`"; DestName: $dest; Flags: ignoreversion; Check: IsAvailable('$hostTok', '$verTok', '$archTok'); AfterInstall: SetupDemandload('$hostTok', '$verTok', '$archTok')"))
}

$utf8bom = New-Object System.Text.UTF8Encoding $true
[System.IO.File]::WriteAllText($FilesIss, (($fileLines -join "`r`n") + "`r`n"), $utf8bom)

# --- HostsCode.iss (Pascal only; no [Code] header) ---
$loaders = @($shipRows)
$probes = [System.Collections.Generic.List[object]]::new()
foreach ($row in $shipRows) {
    $style = [string]$row.reg.loaderStyle
    $adminOnly = ($style -eq 'acadR15')
    # Gold BRX IsAvailable checks CURVER + product key only. Applications is
    # created on first plugin write; requiring it on detect skips a clean install.
    $detectRequiresApps = ([string]$row.family -ne 'BRX')
    foreach ($p in @($row.reg.probes)) {
        [void]$probes.Add([pscustomobject]@{
                Host               = [string]$row.family
                Ver                = [string]$row.version
                Arch               = [string]$row.arch
                CurVerName         = [string]$p.curVerName
                Key                = [string]$p.key
                CurVerHive         = [string]$p.curVerHive
                AppsHive           = [string]$p.appsHive
                WriteRootKind      = Get-WriteRootKind ([string]$p.writeRoot)
                LoaderStyle        = Get-LoaderStyleConst $style
                AdminDetectOnly    = $adminOnly
                DetectRequiresApps = $detectRequiresApps
                DestName           = Get-InnoDestName $row
                RowId              = [string]$row.id
            })
    }
}

