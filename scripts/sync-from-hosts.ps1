$codeText = [System.IO.File]::ReadAllText($CodeIss)
if ($filesText -match '\[Files\]') { throw 'HostsFiles.iss must not contain a [Files] header' }
if ($codeText -match '\[Code\]') { throw 'HostsCode.iss must not contain a [Code] header' }
if ($filesText -match 'ZRX\.2026') { throw 'HostsFiles.iss must not mention ZRX.2026 (no 2026 DestName)' }
if ($codeText -match "\{#MyAppBaseName\}\.ZRX\.2026") { throw 'HostsCode.iss must not use a ZRX.2026 DestName' }
if ($codeText -notmatch "\{#MyAppBaseName\}\.ZRX\.2025\.x64\.zrx") {
    throw 'HostsCode.iss missing ZRX.2025.x64 DestName'
}
if ($codeText -notmatch "SetHostProbe\([^;]*'ZRX', '2025', 'x64', 'CurVer', 'Software\\ZWSOFT\\ZWCAD\\2026'") {
    throw 'ZWCAD 2026 probe is not bound to ZRX Ver 2025'
}
if ($codeText -notmatch 'DetectRequiresApps') {
    throw 'HostsCode.iss must encode DetectRequiresApps'
}
$brxFalse = [regex]::Matches($codeText, "SetHostProbe\([^;]*'BRX'[^;]*False, False\);")
if ($brxFalse.Count -eq 0) {
    throw 'BRX probes must set DetectRequiresApps=False'
}
$zrx2026Probe = $probes | Where-Object { $_.Key -like '*\2026' }
if (-not $zrx2026Probe) { throw 'missing ZWCAD 2026 probe in generated tables' }
foreach ($p in @($zrx2026Probe)) {
    if ($p.Ver -ne '2025') { throw "ZWCAD 2026 probe Ver is '$($p.Ver)' (expected 2025)" }
    if ($p.DestName -notlike '*.ZRX.2025.x64.zrx') { throw "ZWCAD 2026 probe DestName is '$($p.DestName)' (expected 2025)" }
}

Write-Host ("sync-from-hosts.ps1: wrote {0} Source lines, {1} probes, {2} loaders" -f $shipRows.Count, $probes.Count, $loaders.Count)
Write-Host "  $FilesIss"
Write-Host "  $CodeIss"
Write-Host "  $HostsMd"
