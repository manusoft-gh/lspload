[void]$md.AppendLine('## Families')
[void]$md.AppendLine('')
[void]$md.AppendLine('| Family | Ext | Def | Entry | Targets | Ship | Unshipped |')
[void]$md.AppendLine('|--------|-----|-----|-------|---------|------|-----------|')
foreach ($fam in @('ARX', 'BRX', 'ZRX', 'GRX')) {
